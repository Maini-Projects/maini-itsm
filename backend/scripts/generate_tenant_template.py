"""Writes backend/app/tenant_sql/tables.sql and triggers.sql: the tables a single customer owns, read from the live
database so the template always matches what the migrations produced.

Run from the backend folder:  .venv\\Scripts\\python.exe scripts\\generate_tenant_template.py
Everything is written without a schema name; it is executed with search_path = <customer schema>, public.
"""
import os
import re
import sys

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(BACKEND)
import psycopg  # noqa: E402

TABLES = ["incidents", "incident_comments", "problems", "problem_incidents", "defects", "defect_comments", "changes",
          "releases", "release_changes", "approvals", "attachments", "audit_log"]
DROP_COLUMNS = {"project_id"}  # the schema itself says which customer a row belongs to

URL = re.search(r"^DATABASE_URL=(.*)$", open(".env").read(), re.M).group(1).strip().strip("\"'")
out_dir = os.path.join(BACKEND, "app", "tenant_sql")
os.makedirs(out_dir, exist_ok=True)


def unq(s: str) -> str:
    return s.replace("public.", "")


with psycopg.connect(URL, prepare_threshold=None) as c:
    c.execute("set search_path to public")
    tables, fks, triggers = [], [], []

    seqs = c.execute("""select s.relname, q.seqstart from pg_class s join pg_sequence q on q.seqrelid = s.oid
                         join pg_namespace n on n.oid = s.relnamespace
                        where n.nspname = 'public' and s.relkind = 'S' and s.relname !~ '_id_seq$' order by 1""").fetchall()
    used = " ".join(
        r[0] or "" for r in c.execute(
            "select pg_get_expr(adbin, adrelid) from pg_attrdef d join pg_class t on t.oid = d.adrelid "
            "where t.relname = any(%s) and t.relnamespace = 'public'::regnamespace", (TABLES,)).fetchall())
    seq_sql = [f"create sequence {n} start {start};" for n, start in seqs if n in used]

    for t in TABLES:
        cols = c.execute("""select a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attidentity,
                                   pg_get_expr(d.adbin, d.adrelid)
                              from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
                             where a.attrelid = %s::regclass and a.attnum > 0 and not a.attisdropped order by a.attnum""",
                         (f"public.{t}",)).fetchall()
        lines = []
        for name, typ, notnull, identity, default in cols:
            if name in DROP_COLUMNS:
                continue
            line = f"  {name} {typ}"
            if identity == "a":
                line += " generated always as identity"
            elif default:
                line += f" default {unq(default)}"
            if notnull:
                line += " not null"
            lines.append(line)
        cons = c.execute("""select conname, contype, pg_get_constraintdef(oid) from pg_constraint
                             where conrelid = %s::regclass order by contype desc, conname""", (f"public.{t}",)).fetchall()
        for name, typ, definition in cons:
            if any(col in definition for col in DROP_COLUMNS) and typ in "cfpu":
                continue
            if typ in ("p", "u", "c"):
                lines.append(f"  constraint {name} {unq(definition)}")
            elif typ == "f":
                fks.append(f"alter table {t} add constraint {name} {unq(definition)};")
        tables.append(f"create table {t} (\n" + ",\n".join(lines) + "\n);")
        for name, definition in c.execute(
                """select i.indexname, i.indexdef from pg_indexes i
                    where i.schemaname = 'public' and i.tablename = %s
                      and not exists (select 1 from pg_constraint k where k.conname = i.indexname)""", (t,)).fetchall():
            if not any(col in definition for col in DROP_COLUMNS):
                tables.append(unq(definition) + ";")
        for (definition,) in c.execute(
                "select pg_get_triggerdef(oid) from pg_trigger where tgrelid = %s::regclass and not tgisinternal order by tgname",
                (f"public.{t}",)).fetchall():
            d = re.sub(r"function audit_row\(\)", "FUNCTION tenant_audit_row()", unq(definition), flags=re.I)
            triggers.append(d + ";")
        tables.append(f"alter table {t} enable row level security;")

    header = "-- Generated by backend/scripts/generate_tenant_template.py. Run with search_path = <customer schema>, public.\n\n"
    open(os.path.join(out_dir, "tables.sql"), "w", encoding="utf8").write(
        header + "\n".join(seq_sql) + "\n\n" + "\n\n".join(tables) + "\n\n" + "\n".join(fks) + "\n")
    open(os.path.join(out_dir, "triggers.sql"), "w", encoding="utf8").write(header + "\n".join(triggers) + "\n")
    print("tables:", len(TABLES), "sequences:", len(seq_sql), "foreign keys:", len(fks), "triggers:", len(triggers))
